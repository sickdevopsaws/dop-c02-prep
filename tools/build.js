#!/usr/bin/env node
// Merges data/*.json into questions.js and validates every question.
// Usage: node tools/build.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dataDir = path.join(root, 'data');
const DOMAINS = ['sdlc', 'iac', 'resilience', 'monitoring', 'incident', 'security'];

const errors = [];
const all = [];
const ids = new Set();

for (const file of fs.readdirSync(dataDir).filter(f => f.endsWith('.json')).sort()) {
  let list;
  try {
    list = JSON.parse(fs.readFileSync(path.join(dataDir, file), 'utf8'));
  } catch (e) {
    errors.push(`${file}: invalid JSON (${e.message})`);
    continue;
  }
  for (const q of list) {
    const where = `${file}:${q.id || '?'}`;
    if (!q.id) errors.push(`${where}: missing id`);
    if (ids.has(q.id)) errors.push(`${where}: duplicate id`);
    ids.add(q.id);
    if (!DOMAINS.includes(q.domain)) errors.push(`${where}: unknown domain "${q.domain}"`);
    for (const k of ['topic', 'scenario', 'question', 'takeaway']) {
      if (!q[k] || typeof q[k] !== 'string') errors.push(`${where}: missing ${k}`);
    }
    if (!Array.isArray(q.options) || q.options.length < 4) errors.push(`${where}: needs >= 4 options`);
    const correct = (q.options || []).filter(o => o.correct).length;
    if (correct !== q.select) errors.push(`${where}: select=${q.select} but ${correct} correct`);
    (q.options || []).forEach((o, i) => {
      if (!o.text || !o.why) errors.push(`${where}: option ${i} missing text/why`);
    });
    all.push(q);
  }
}

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const out = `// Generated by tools/build.js — edit data/*.json instead.\nwindow.QUESTIONS = ${JSON.stringify(all)};\n`;
fs.writeFileSync(path.join(root, 'questions.js'), out);

const counts = Object.fromEntries(DOMAINS.map(d => [d, all.filter(q => q.domain === d).length]));
console.log(`${all.length} questions`, counts);
